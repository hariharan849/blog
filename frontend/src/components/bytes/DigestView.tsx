import Link from "next/link";

import ArticleCard from "./ArticleCard";

import { formatDate } from "@/lib/format";
import type { Digest } from "@/lib/types";

export default function DigestView({ digest, isLatest }: { digest: Digest; isLatest: boolean }) {
  return (
    <div className="space-y-10">
      <section className="relative overflow-hidden rounded-3xl bg-gradient-to-br from-indigo-600 via-violet-600 to-fuchsia-600 p-8 text-white shadow-xl shadow-indigo-500/20 sm:p-10">
        <div aria-hidden className="cover-pattern absolute inset-0 opacity-60" />
        <div className="relative">
          <p className="text-sm text-white/80">
            {formatDate(digest.date)}
            {!isLatest && <> · <Link href="/bytes/" className="underline underline-offset-2">latest</Link></>}
          </p>
          <h2 className="mt-2 max-w-3xl font-serif text-3xl font-semibold leading-tight sm:text-4xl">{digest.headline}</h2>
          {digest.intro && <p className="mt-4 max-w-2xl text-white/85">{digest.intro}</p>}
        </div>
      </section>

      {digest.takeaways.length > 0 && (
        <section aria-labelledby="byte-heading">
          <h2 id="byte-heading" className="text-sm font-semibold uppercase tracking-wider text-zinc-500">Today&apos;s byte</h2>
          <ol className="mt-4 grid gap-4 md:grid-cols-2">
            {digest.takeaways.map((takeaway, index) => (
              <li key={takeaway.title} className="rounded-2xl border border-zinc-200 p-5 dark:border-zinc-800">
                <span className="font-mono text-xs text-indigo-500">{String(index + 1).padStart(2, "0")}</span>
                <p className="mt-1 font-semibold">{takeaway.title}</p>
                <p className="mt-2 text-sm text-zinc-600 dark:text-zinc-400">{takeaway.explanation}</p>
                {takeaway.source_urls.length > 0 && (
                  <p className="mt-3 flex gap-3 text-xs">
                    {takeaway.source_urls.map((url, i) => (
                      <a key={url} href={url} target="_blank" rel="noopener noreferrer" className="text-indigo-600 hover:underline dark:text-indigo-400">source {i + 1} ↗</a>
                    ))}
                  </p>
                )}
              </li>
            ))}
          </ol>
          {digest.try_today && (
            <p className="mt-4 rounded-2xl border border-emerald-200 bg-emerald-50 p-5 text-sm text-emerald-900 dark:border-emerald-900/60 dark:bg-emerald-950/30 dark:text-emerald-200">
              <strong>Try today:</strong> {digest.try_today}
            </p>
          )}
        </section>
      )}

      <section aria-labelledby="reading-heading">
        <h2 id="reading-heading" className="text-sm font-semibold uppercase tracking-wider text-zinc-500">Reading list</h2>
        <div className="mt-4 space-y-4">
          {digest.articles.length ? (
            digest.articles.map((article) => <ArticleCard key={article.id} article={article} />)
          ) : (
            <p className="rounded-2xl border border-dashed border-zinc-300 p-8 text-center text-zinc-500 dark:border-zinc-700">
              Nothing passed your relevance threshold today. Browse <Link href="/bytes/articles/" className="text-indigo-600 dark:text-indigo-400">all articles</Link>.
            </p>
          )}
        </div>
      </section>
      <p className="text-xs text-zinc-500 dark:text-zinc-400">Generated by {digest.generated_by}</p>
    </div>
  );
}
