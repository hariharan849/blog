import Link from "next/link";

import ArticleCard from "./ArticleCard";

import { formatDate } from "@/lib/format";
import type { Digest } from "@/lib/types";

export default function DigestView({ digest, isLatest }: { digest: Digest; isLatest: boolean }) {
  return (
    <>
      <p className="text-muted mb-1">
        {formatDate(digest.date)}
        {!isLatest && <> · <Link href="/bytes/">latest</Link></>}
      </p>
      <h1 className="mb-3">{digest.headline}</h1>
      {digest.intro && <p className="lead">{digest.intro}</p>}
      {digest.takeaways.length > 0 && (
        <div className="card mb-4 border-primary">
          <div className="card-header">Today&apos;s byte</div>
          <div className="card-body">
            <ol className="mb-0">
              {digest.takeaways.map((takeaway) => (
                <li className="mb-3" key={takeaway.title}>
                  <strong>{takeaway.title}</strong>
                  <br />
                  {takeaway.explanation}
                  {takeaway.source_urls.map((url, index) => (
                    <a key={url} href={url} target="_blank" rel="noopener noreferrer" className="small ms-1">[source {index + 1}]</a>
                  ))}
                </li>
              ))}
            </ol>
          </div>
          {digest.try_today && (
            <div className="card-footer"><strong>Try today:</strong> {digest.try_today}</div>
          )}
        </div>
      )}
      <h2 className="h4 mb-3">Reading list</h2>
      {digest.articles.length ? (
        digest.articles.map((article) => <ArticleCard key={article.id} article={article} />)
      ) : (
        <p className="text-muted">
          Nothing passed your relevance threshold today. Browse <Link href="/bytes/articles/">all articles</Link>.
        </p>
      )}
      <p className="text-muted small">Generated by {digest.generated_by}</p>
    </>
  );
}
