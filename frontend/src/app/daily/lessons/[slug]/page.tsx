import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { getLesson, getLessons, getRelated } from "@/lib/posts";
import { formatDate, SITE_URL } from "@/lib/format";
import ShareLinks from "@/components/ShareLinks";
import TableOfContents from "@/components/TableOfContents";
import ReadingProgress from "@/components/ReadingProgress";
import RelatedReading from "@/components/RelatedReading";
import SubscribeForm from "@/components/SubscribeForm";

type Props = { params: Promise<{ slug: string }> };

export const dynamicParams = false;

export function generateStaticParams() {
  return getLessons().map((l) => ({ slug: l.slug }));
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const lesson = getLesson((await params).slug);
  if (!lesson) return {};
  return {
    title: lesson.title,
    description: lesson.summary,
    openGraph: { type: "article", title: lesson.title, description: lesson.summary, publishedTime: lesson.date },
  };
}

export default async function LessonPage({ params }: Props) {
  const lesson = getLesson((await params).slug);
  if (!lesson) notFound();

  return (
    <article className="narrow">
      <ReadingProgress />
      <header className="hero">
        <p className="eyebrow">
          <Link href="/daily/lessons">Daily lesson</Link>
        </p>
        <p className="meta">
          <time dateTime={lesson.date}>{formatDate(lesson.date, { month: "long" })}</time> · {lesson.readingMinutes} min
          read
        </p>
        <h1 className="post-title">{lesson.title}</h1>
        {lesson.tags.length > 0 && (
          <p className="tag-row">
            {lesson.tags.map((t) => (
              <span key={t} className="badge badge-muted">
                #{t}
              </span>
            ))}
          </p>
        )}
      </header>
      {/* Lessons are Markdown files generated by lessons/make_lesson.py and committed to this repo. */}
      <TableOfContents toc={lesson.toc} />
      <div className="prose" dangerouslySetInnerHTML={{ __html: lesson.html }} />
      <RelatedReading items={getRelated("lesson", lesson.slug)} />
      <hr />
      <SubscribeForm compact />
      <ShareLinks title={lesson.title} url={`${SITE_URL}/daily/lessons/${lesson.slug}`} />
      <Link href="/daily/lessons" className="button button-secondary">
        ← All lessons
      </Link>
    </article>
  );
}
